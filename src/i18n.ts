export type SupportedLanguage = 'en' | 'ja' | 'es' | 'fr';

export function detectLanguage(context: any): SupportedLanguage {
  const locale = String(context.user?.locale || context.locale || 'en').toLowerCase();
  if (locale.startsWith('ja') || locale.includes('jp')) return 'ja';
  if (locale.startsWith('es')) return 'es';
  if (locale.startsWith('fr')) return 'fr';
  return 'en';
}

export function t(
  key: string,
  lang: SupportedLanguage,
  vars?: Record<string, string | number>
): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let text = dict[key] ?? TRANSLATIONS.en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return text;
}

